// tests/static/fresh_clone.test.mjs — a source that exists here but not in git.
//
// The root .gitignore excludes *.json, so a new JSON source is silently left out
// of every commit unless the subtree's allow-list names it. config/rubric_v6.json
// — the file every generator declares as its source — sat that way from 17 Sep
// to 24 Sep: the maintainer's tree built and passed, and a fresh clone failed 13
// of 194 test files on ENOENT. This test runs in the tree where that mistake is
// made, and fails while any file in a source directory is present but ignored.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const SOURCE_DIRS = ['config', 'engine', 'clay/code', 'n8n/nodes', 'n8n/patch', 'scripts', 'tests'];

// Local by design, each for a stated reason in .gitignore: live account keys,
// build output (regenerated by `pretest`), caches.
const LOCAL_ONLY = [
  /\.local\.json$/,
  /(^|\/)__pycache__\//,
  /^tests\/golden\/\.cache\//,
  /(^|\/)node_modules\//,
];

test('every file in a source directory that exists here is in git', (t) => {
  let out;
  try {
    out = execFileSync('git', ['ls-files', '--others', '--ignored', '--exclude-standard', '--', ...SOURCE_DIRS],
      { cwd: ROOT, encoding: 'utf8' });
  } catch {
    t.skip('not a git checkout');
    return;
  }
  const hidden = out.split('\n').filter(Boolean).filter((f) => !LOCAL_ONLY.some((re) => re.test(f)));
  assert.deepEqual(hidden, [],
    'present on disk but ignored by git, so a fresh clone does not have it — ' +
    'name it in icp-scoring/.gitignore\'s allow-list, or add it to LOCAL_ONLY with a reason');
});
