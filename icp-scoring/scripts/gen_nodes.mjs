#!/usr/bin/env node
// scripts/gen_nodes.mjs — generate the two Code nodes that would otherwise
// duplicate tested logic.
//
// An n8n Code node cannot import. So a node that needs identifier
// normalization or the scoring arithmetic has to carry a copy — and a
// hand-maintained copy of tested logic is the drift that ships wrong grades.
//
// Both copies are therefore SPLICED IN from their single source:
//
//   BuildClayRequest.js  <- engine/normalize.mjs, verbatim minus `export`
//   ParseScored.js       <- engine/validate_event.mjs, the Path B boundary
//
// v5 spliced the SCORER here so n8n could recompute Clay's grade and flag
// drift. v6.0 went further and moved scoring into n8n outright. Both are gone:
// the table scores, n8n writes, and the only thing spliced now is the
// validator — the rule that rejects an event is the same source its unit tests
// exercise.
//
// Run: npm run gen:nodes

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NODES = join(ROOT, 'n8n', 'nodes');

const BANNER = (sources) => `// GENERATED by scripts/gen_nodes.mjs. Do not edit by hand.
// Spliced from: ${sources.join(', ')}
// tests/static/nodes_execute.test.mjs asserts the spliced copy behaves
// identically to its source, and workflow_review.test.mjs asserts this file is
// byte-identical to the jsCode deployed in WF-ICP-Score.dev.json.
`;

const indent = (text, pad) => text.split('\n')
  .map((line) => (line.trim() === '' ? '' : pad + line)).join('\n');

// ---------------------------------------------------------------------------
// engine/normalize.mjs, ready to inline
// ---------------------------------------------------------------------------
function inlineNormalizer() {
  const source = readFileSync(join(ROOT, 'engine', 'normalize.mjs'), 'utf8');
  if (/^\s*import\s/m.test(source)) {
    throw new Error('engine/normalize.mjs gained an import — it can no longer be inlined into a Code node');
  }
  // Drop the file header (everything before the first declaration) and turn
  // module exports into plain declarations.
  const start = source.indexOf('export const PUBLIC_SUFFIXES');
  if (start === -1) throw new Error('cannot find PUBLIC_SUFFIXES in engine/normalize.mjs');
  return source.slice(start).replace(/^export /gm, '');
}

// ---------------------------------------------------------------------------
// engine/validate_event.mjs, ready to inline
//
// Same trick as the normalizer: an n8n Code node cannot import, so the file is
// written with no imports and its `export` keywords are stripped here. The
// rule that rejects a scored event is therefore the same source the unit tests
// exercise, not a second copy of it.
// ---------------------------------------------------------------------------
function inlineValidator() {
  const source = readFileSync(join(ROOT, 'engine', 'validate_event.mjs'), 'utf8');
  if (/^\s*import\s/m.test(source)) {
    throw new Error('engine/validate_event.mjs gained an import — it can no longer be inlined into a Code node');
  }
  const start = source.indexOf('export const GRADES');
  if (start === -1) throw new Error('cannot find GRADES in engine/validate_event.mjs');
  return source.slice(start).replace(/^export /gm, '');
}



// ===========================================================================
// BuildClayRequest
// ===========================================================================
const buildClayRequest = `${BANNER(['engine/normalize.mjs'])}//
// BuildClayRequest — the body POSTed to the Clay ICP_Engine webhook source.
//
// Nulls are SENT as null, never omitted and never "". This is a deliberate
// departure from the omit-null default: Clay's facts_json must be able to tell
// "enrichment did not find it" from "we never asked", and the classifier
// prompts instruct the model to read null as the former. An omitted key
// destroys that distinction.

const cfg = $('CONFIG').item.json;
const gate = $('IdempotencyGate').item.json;

${inlineNormalizer()}

// ---------------------------------------------------------------------------
// The one identifier: the organization's website, normalised to a domain.
//
// Mandatory, and "mandatory" is enforced here rather than hoped for. A blank, a
// typo, "n/a", a bare word with no dot — all of them come back null from the
// normalizer, and null means this organization is NOT sent to Clay. There is no
// name lookup and no LinkedIn fallback: a name search that resolves the wrong
// company of the same name scores a stranger's record and looks exactly like a
// correct run. Six organizations named Sumersports is what that failure looks
// like from the inside.
//
// A missing website is NOT an error. It is an ordinary outcome with an
// ordinary result — "n/a - no website" on the record and one activity saying
// what to do about it — so it returns a decision rather than throwing, and the
// IF node downstream stays a pure read.
// ---------------------------------------------------------------------------
const domain = normalizeDomain(gate.org_website);

// A directory is not a company. linkedin.com, crunchbase.com, a Wix subdomain
// — these normalise perfectly and are exactly as wrong as a name lookup: send
// "linkedin.com" and the table enriches LinkedIn Corporation, then a rep reads
// a confident A on an account that was never looked at. NON_COMPANY_HOSTS is
// the same list the Phase 0 coverage audit was measured against.
const usable = domain !== null && !NON_COMPANY_HOSTS.has(domain);

if (!usable) {
  let reason;
  if (!gate.org_website) reason = 'organization has no Website URL';
  else if (domain === null) reason = \`website "\${gate.org_website}" is not a usable domain\`;
  else reason = \`website "\${gate.org_website}" points at \${domain}, which is a directory rather than the company\`;

  return [{
    json: {
      has_website: false,
      request_id: gate.request_id,
      org_id: gate.org_id,
      deal_id: gate.deal_id,
      website_raw: gate.org_website === undefined ? null : gate.org_website,
      reason,
    },
  }];
}

// Pipedrive ids are numbers on the wire, both ways: the table's columns are
// typed, and a column that is sometimes "2695" and sometimes 2695 does not join
// against anything. They stay STRINGS inside this workflow, where they are
// identifiers and never arithmetic — Normalize is explicit about that — so the
// conversion happens here, at the boundary, and nowhere else.
const wireId = (value) => {
  if (value === null || value === undefined || value === '') return null;
  const n = Number(value);
  return Number.isFinite(n) ? n : null;
};

// Seven keys. Not six, not eight — the table's input columns are these, and a
// key the table does not have a column for is a key that vanishes silently.
const body = {
  org_id: wireId(gate.org_id),
  deal_id: wireId(gate.deal_id),
  domain,
  request_id: gate.request_id,
  callback_url: cfg.clay_callback_url,
  // The table's AI columns use this as "today" for days-open arithmetic on job
  // postings. It comes from CONFIG rather than from $now here so that every
  // node in one execution agrees on the same instant — a run that straddles
  // midnight must not tell the table one date and the record another.
  requested_at: cfg.now_iso,
  model_version: cfg.model_version,
};

return [{
  json: {
    has_website: true,
    request_id: gate.request_id,
    org_id: gate.org_id,
    deal_id: gate.deal_id,
    domain,
    clay_url: cfg.clay_engine_url,
    body,
  },
}];
`;

// ===========================================================================
// ParseScored
// ===========================================================================
const parseScored = `${BANNER(['engine/validate_event.mjs'])}//
// ParseScored — Path B's boundary, and now its only thinking.
//
// The table scores. This node checks that what arrived is something that can
// be WRITTEN — a grade, a status, a note — and then hands it on flat. It
// computes nothing: v6.0 had a Score node holding the rubric, and running a
// second rubric in n8n to agree with Clay's was two implementations pretending
// to be one.
//
// The validator is spliced from engine/validate_event.mjs, which has its own
// unit tests, so the rule that rejects an event is the rule the tests exercise.

// CONFIG on Path A, CONFIG B on Path B. The two Set nodes hold the same JSON,
// but a Code node may only reference a node that is CONNECTED upstream of it:
// n8n raises a "no connection" expression error otherwise, and in the task
// runner that error's own constructor then throws
// \`Cannot assign to read only property 'name'\`, which hides the real message
// completely. A node that runs on both paths therefore has to ask for
// whichever CONFIG is upstream of it. Kept byte-identical across the nodes
// that need it; tests/static/workflow_review.test.mjs enforces that.
let cfg = null;
try { cfg = $('CONFIG').item.json; } catch (e) { cfg = null; }
if (cfg === null || cfg === undefined) {
  try { cfg = $('CONFIG B').item.json; } catch (e) { cfg = null; }
}
if (cfg === null || cfg === undefined) {
  throw new Error('ICP_NO_CONFIG: neither CONFIG nor CONFIG B is upstream of this node');
}
const item = $input.first().json;
const raw = item.body || {};

${inlineValidator()}

const problems = validateEvent(raw, cfg);

if (problems.length > 0) {
  const error = new Error(
    \`ICP_MALFORMED_EVENT: \${problems.length} problem(s) in the scored event for \` +
    \`request_id=\${raw.request_id || '(none)'}: \${problems.join('; ')}\`
  );
  error.name = 'IcpMalformedEvent';
  error.problems = problems;
  error.request_id = raw.request_id || null;
  error.org_id = raw.org_id || null;
  throw error;
}

// Flat, and in one place, so BuildOrgPatch / BuildActivity / BuildRunSummary
// all read the same object rather than three readings of the raw body.
const opt = (key) => (raw[key] === undefined ? null : raw[key]);

return [{
  json: {
    _path: 'B',
    _dedupe_key: item._dedupe_key,
    _duplicate: item._duplicate === true,
    _rate_this_hour: item._rate_this_hour,
    _rate_exceeded: item._rate_exceeded === true,

    request_id: raw.request_id,
    org_id: raw.org_id,
    deal_id: raw.deal_id === undefined ? null : raw.deal_id,
    requested_at: raw.requested_at,

    final: raw.final,
    grade: raw.grade,
    status: raw.status,
    // Verbatim. Not trimmed, not reflowed, not re-rendered. The table wrote
    // what the rep reads and there is exactly one author of it.
    note: raw.note,

    composite: opt('composite'),
    multiplier: opt('multiplier'),
    final_without_activation: opt('final_without_activation'),
    industry_level: opt('industry_level'),
    stage_level: opt('stage_level'),
    type_level: opt('type_level'),
    geo_level: opt('geo_level'),
    revenue_level: opt('revenue_level'),
    activation_used: opt('activation_used'),
    confidence_overall: opt('confidence_overall'),
    tier2_candidate: opt('tier2_candidate'),
    flags: raw.flags === undefined || raw.flags === null ? [] : raw.flags,

    model_version: cfg.model_version,
  },
}];
`;

// ===========================================================================
// BuildErrorContext
// ===========================================================================
//
// Generated for ONE reason: so the validator can be spliced into it.
//
// n8n's task runner does not carry a thrown error's own properties across an
// error output. Execution 60648 threw an IcpMalformedEvent listing every
// violation; what arrived at this node was "unknown error", zero problems, and
// the Slack alert that came out of it told nobody anything they could act on.
//
// So this node does not try to recover the problem list from the error. It
// re-runs the same validator over the body the webhook received — intact
// whatever failed downstream — and gets the list back in full.
//
// The skeleton lives in n8n/nodes/src/BuildErrorContext.src.js with a
// @@VALIDATOR@@ marker, rather than being a template literal here, because a
// node whose own comments contain backticks and ${...} cannot survive being
// one.
function buildErrorContextSource() {
  const skeleton = readFileSync(join(ROOT, 'n8n', 'nodes', 'src', 'BuildErrorContext.src.js'), 'utf8');
  if (!skeleton.includes('@@VALIDATOR@@')) {
    throw new Error('BuildErrorContext.src.js lost its @@VALIDATOR@@ marker');
  }
  return BANNER(['n8n/nodes/src/BuildErrorContext.src.js', 'engine/validate_event.mjs'])
    + skeleton.replace('// @@VALIDATOR@@', inlineValidator());
}
const buildErrorContext = buildErrorContextSource();

writeFileSync(join(NODES, 'BuildClayRequest.js'), buildClayRequest, 'utf8');
writeFileSync(join(NODES, 'ParseScored.js'), parseScored, 'utf8');
writeFileSync(join(NODES, 'BuildErrorContext.js'), buildErrorContext, 'utf8');

process.stdout.write(
  `wrote n8n/nodes/BuildClayRequest.js (${buildClayRequest.length} bytes)\n` +
  `wrote n8n/nodes/ParseScored.js (${parseScored.length} bytes)\n` +
  `wrote n8n/nodes/BuildErrorContext.js (${buildErrorContext.length} bytes)\n`
);
